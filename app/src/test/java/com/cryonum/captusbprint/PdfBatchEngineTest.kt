package com.cryonum.captusbprint

import com.cryonum.captusbprint.core.CaptFrame
import com.cryonum.captusbprint.core.CaptJobProtocol as P
import com.cryonum.captusbprint.core.CaptTestPage
import com.cryonum.captusbprint.document.PreparedPdfCaptPageBuilder
import com.cryonum.captusbprint.usb.CaptDocumentPrintEngine
import com.cryonum.captusbprint.usb.CaptPdfBatchPrintEngine
import com.cryonum.captusbprint.usb.CaptTestPrintResult
import com.cryonum.captusbprint.usb.PdfBatchSession
import org.junit.Assert.*
import org.junit.Test
import java.io.IOException

class PdfBatchEngineTest {
    // Fixed owner-captured frames, not responses generated by the engine under test.
    private fun hex(value: String) = value.split(" ").map { it.toInt(16).toByte() }.toByteArray()
    private val info = hex("A1 A1 38 00 00 0B 31 2A 01 01 F0 FF 40 00 04 00 41 00 01 00 D0 02 00 00 6F 08 00 00 E4 0D 00 00 00 00 00 00 FA 02 00 00 F6 04 00 00 28 3C 32 32 58 02 58 02 15 03 02 00")
    private val observed = hex("A8 A0 38 00 01 88 00 00 0F 00 00 00 00 00 80 00 00 00 02 00 02 00 02 00 02 00 00 00 57 00 00 00 01 00 00 00 00 05 02 00 00 00 00 00 00 00 00 00 01 00 00 00 00 00 00 00")
    private val sheet by lazy {
        PreparedPdfCaptPageBuilder.prepare(
            produceBands = { accept ->
                var y = 0
                while (y < CaptTestPage.HEIGHT) {
                    val lines = minOf(64, CaptTestPage.HEIGHT - y)
                    accept(y, ByteArray(620 * lines))
                    y += lines
                }
            },
            encode = { _, _, _, _ -> byteArrayOf(17) }
        )
    }

    private inner class Printer : PdfBatchSession {
        val commands = ArrayList<Int>()
        val flags = ArrayList<Int>()
        val starts = ArrayList<Int>()
        var descriptors = 0
        var closed = false
        var decoded = 2
        var completed = 2
        var offline = false
        var basic = 1
        var inputPending = false
        var refuseReserve = false
        var stalledPage = 0
        var disconnectOnPage = 0
        var noPaperOnPage = 0
        var rejectEnd = false
        var rejectAck: Int? = null
        var bufferSlots = 15
        var drainOnStart = false
        var onBasic: () -> Unit = {}

        override fun query(command: Int, payload: ByteArray): ByteArray {
            commands.add(command)
            if (command == rejectAck) return CaptFrame.encode(command, byteArrayOf(0x88.toByte(), 0))
            when (command) {
                P.GET_PRINTER_INFO -> return info.copyOf()
                P.GET_BASIC_STATUS -> {
                    onBasic()
                    return hex("A0 E0 06 00 01 00").also {
                        it[4] = basic.toByte()
                        if (inputPending) it[5] = 2
                    }
                }
                P.GET_INPUT_STATUS -> {
                    inputPending = false
                    return hex("A1 A0 16 00 00 10 C0 00 00 00 00 00 00 00 96 00 FD 00 00 00 00 00")
                }
                P.RESERVE_UNIT -> return if (refuseReserve) hex("A0 A2 08 00 8C 00 00 00")
                    else hex("A0 A2 08 00 00 00 2A 00")
                P.GO_OFFLINE -> offline = true
                P.GO_ONLINE -> { offline = false; decoded = 0; completed = 0 }
                P.SET_JOB_INFO2 -> {
                    flags.add(payload[16].toInt())
                    assertEquals(42, payload[18].toInt())
                    if (rejectEnd && payload[16].toInt() == 6) throw IOException("Uncertain end reply")
                }
                P.SET_POWER_DOWN, P.DISCARD_DATA, P.CLEAR_MIS_PRINT, P.CLEAR_ERROR, P.RELEASE_UNIT -> Unit
                P.START_PRINT -> {
                    val number = payload[0].toInt() and 255
                    starts.add(number)
                    if (drainOnStart) bufferSlots = 15
                    if (number != stalledPage) completed = number
                }
                P.GET_EXTENDED_STATUS -> return observed.copyOf().also {
                    it[4] = if (offline) 0x11 else 1
                    it[5] = if (inputPending) 0x8a.toByte() else 0x88.toByte()
                    it[8] = bufferSlots.toByte()
                    if (descriptors > 0 && decoded == noPaperOnPage && noPaperOnPage > 0) it[14] = 0
                    for (offset in listOf(18, 38)) { it[offset] = decoded.toByte(); it[offset + 1] = 0 }
                    for (offset in listOf(20, 22, 24)) { it[offset] = completed.toByte(); it[offset + 1] = 0 }
                }
                else -> error("Unexpected query $command")
            }
            return CaptFrame.encode(command, byteArrayOf(0, 0))
        }

        override fun sendFrame(frame: ByteArray) {
            val command = (frame[0].toInt() and 255) or ((frame[1].toInt() and 255) shl 8)
            if (command == 0xD0A9) {
                // The production runner must finish the preceding sheet before this call.
                assertEquals(descriptors, completed)
                descriptors++
                decoded = descriptors
            } else {
                assertEquals(0xC0A0, command)
                if (descriptors == disconnectOnPage) throw IOException("USB disconnected during frame")
            }
        }

        override fun sendOnly(command: Int) { assertEquals(0xC0A4, command) }
        override fun close() { closed = true }
    }

    private fun run(printer: Printer, pages: Int = 3,
                    cancelled: () -> Boolean = { false },
                    progress: (String) -> Unit = {},
                    checkpoint: (CaptTestPrintResult) -> Unit = {}): CaptTestPrintResult {
        var millis = 0L
        return CaptDocumentPrintEngine.runPrepared(List(pages) { sheet }, cancelled,
            progress, checkpoint, { printer }, { millis }, { millis += it })
    }

    @Test fun generalOneAndTenSheetJobsKeepExactCountsAndOneReservation() {
        for (pages in listOf(1, 10)) {
            val printer = Printer()
            val result = run(printer, pages)
            assertEquals(result.trace.joinToString("\n"), "printer_counter_confirmed", result.outcome)
            assertEquals(pages, result.printerConfirmedPages)
            assertEquals((1..pages).toList(), printer.starts)
            assertEquals(if (pages == 1) listOf(1,6) else listOf(1,2,6), printer.flags)
            assertEquals(1, printer.commands.count { it == P.RESERVE_UNIT })
        }
    }

    @Test fun threeSheetsUseOneJobAndOneContinuationIncludingTheThirdCounter() {
        val printer = Printer()
        val saved = ArrayList<Int?>()
        val result = run(printer, checkpoint = { saved.add(it.printerConfirmedPages) })
        assertEquals(result.trace.joinToString("\n"), "printer_counter_confirmed", result.outcome)
        assertEquals(3, result.printerConfirmedPages)
        assertEquals(listOf(1, 2, 3), printer.starts)
        assertEquals(listOf(1, 2, 6), printer.flags)
        assertEquals(listOf(1, 2, 3), saved)
        assertEquals(3, printer.descriptors)
        assertEquals(1, printer.commands.count { it == P.RESERVE_UNIT })
        assertEquals(1, printer.commands.count { it == P.RELEASE_UNIT })
        assertTrue(printer.closed)
    }

    @Test fun twoCopiesReuseOnePreparedPageButProduceExactlyTwoSheets() {
        val printer = Printer()
        val result = run(printer, pages = 2)
        assertEquals(result.trace.joinToString("\n"), "printer_counter_confirmed", result.outcome)
        assertEquals(listOf(1, 2), printer.starts)
        assertEquals(listOf(1, 2, 6), printer.flags)
        assertEquals(2, printer.descriptors)
    }

    @Test fun boundedBufferDrainStartsEachSheetOnlyOnce() {
        val printer = Printer().apply { bufferSlots = 0; drainOnStart = true }
        val result = run(printer)
        assertEquals(result.trace.joinToString("\n"), "printer_counter_confirmed", result.outcome)
        assertEquals(listOf(1, 2, 3), printer.starts)
        assertEquals(listOf(1, 2, 6), printer.flags)
        assertTrue(result.trace.any { it.contains("during bounded buffer drain") })
        assertTrue(printer.closed)
    }

    @Test fun persistentCapturedConflictStopsBeforeReserveAndRetainsBothReplies() {
        val printer = Printer().apply { basic = 0x88 }
        val result = run(printer)
        assertEquals("failed_before_print_commands", result.outcome)
        assertEquals("CAPT_STATUS_CONFLICT", result.failureCode)
        assertTrue(result.trace.any { it.contains("A0 E0 06 00 88 00") })
        assertTrue(result.trace.any { it.contains("A8 A0 38 00 01 88") })
        assertEquals(21, printer.commands.count { it == P.GET_BASIC_STATUS })
        assertFalse(printer.commands.contains(P.RESERVE_UNIT))
        assertTrue(printer.commands.all { it == P.GET_PRINTER_INFO ||
            it == P.GET_BASIC_STATUS || it == P.GET_EXTENDED_STATUS })
        assertEquals(0, result.sentPrintDataBytes.toInt())
        assertEquals(0, printer.descriptors)
        assertTrue(printer.closed)
    }

    @Test fun inputStatusIsSettledBeforeExactlyOneReservation() {
        val printer = Printer().apply { inputPending = true }
        val result = run(printer, pages = 1)
        assertEquals(result.trace.joinToString("\n"), "printer_counter_confirmed", result.outcome)
        assertTrue(printer.commands.indexOf(P.GET_INPUT_STATUS) < printer.commands.indexOf(P.RESERVE_UNIT))
        assertEquals(2, printer.commands.count { it == P.GET_BASIC_STATUS })
        assertEquals(1, printer.commands.count { it == P.RESERVE_UNIT })
        assertEquals(listOf(1), printer.starts)
    }

    @Test fun cancellationDuringReadOnlyReconciliationNeverReserves() {
        var stop = false
        val printer = Printer().apply { onBasic = { stop = true } }
        val result = run(printer, cancelled = { stop })
        assertEquals("failed_before_print_commands", result.outcome)
        assertFalse(printer.commands.contains(P.RESERVE_UNIT))
        assertEquals(0, printer.descriptors)
        assertTrue(printer.closed)
    }

    @Test fun capturedReserveFailureIsUncertainAndNeverReplayedOrReleased() {
        val printer = Printer().apply { refuseReserve = true }
        val result = run(printer)
        assertEquals(result.trace.joinToString("\n"), "unknown_after_print_command", result.outcome)
        assertEquals("A0 A2 08 00 8C 00 00 00", result.lastStatusFrameHex)
        assertEquals(1, printer.commands.count { it == P.RESERVE_UNIT })
        assertEquals(P.RESERVE_UNIT, printer.commands.last())
        assertEquals(0, printer.descriptors)
        assertTrue(printer.closed)
    }

    @Test fun cancellationAfterFirstConfirmationNeverSubmitsSecondPage() {
        val printer = Printer()
        var stop = false
        val result = run(printer, cancelled = { stop }, checkpoint = { stop = true })
        assertEquals(result.trace.joinToString("\n"), "unknown_after_print_command", result.outcome)
        assertEquals(1, result.printerConfirmedPages)
        assertEquals(1, printer.descriptors)
        assertEquals(listOf(1), printer.starts)
        assertFalse(printer.commands.contains(P.RELEASE_UNIT))
        assertTrue(printer.closed)
    }

    @Test fun unconfirmedSecondPageTimesOutWithoutThirdPageOrResend() {
        val printer = Printer().apply { stalledPage = 2 }
        val result = run(printer)
        assertEquals(result.trace.joinToString("\n"), "unknown_after_print_command", result.outcome)
        assertEquals("PAGE_2_WAITING_CONFIRMATION", result.stage)
        assertEquals(1, result.printerConfirmedPages)
        assertEquals(listOf(1, 2), printer.starts)
        assertEquals(2, printer.descriptors)
        assertTrue(printer.closed)
    }

    @Test fun partialWriteAndPaperLossPreserveFirstSheetAndDoNotReplay() {
        for (paperLoss in listOf(false, true)) {
            val printer = Printer().apply {
                if (paperLoss) noPaperOnPage = 2 else disconnectOnPage = 2
            }
            val result = run(printer)
            assertEquals(result.trace.joinToString("\n"), "unknown_after_print_command", result.outcome)
            assertEquals(1, result.printerConfirmedPages)
            assertEquals(2, printer.descriptors)
            assertEquals(listOf(1), printer.starts)
            assertTrue(printer.closed)
        }
    }

    @Test fun failedCheckpointStopsBeforeAnyNextCommand() {
        val printer = Printer()
        val result = run(printer, checkpoint = { throw IOException("Disk full") })
        assertEquals(result.trace.joinToString("\n"), "unknown_after_print_command", result.outcome)
        assertEquals(1, result.printerConfirmedPages)
        assertEquals(1, printer.descriptors)
        assertEquals(listOf(1), printer.flags)
        assertTrue(printer.closed)
    }

    @Test fun failedFinalizationDoesNotClaimWholeJobSuccess() {
        val printer = Printer().apply { rejectEnd = true }
        val result = run(printer)
        assertEquals(result.trace.joinToString("\n"), "unknown_after_print_command", result.outcome)
        assertEquals(3, result.printerConfirmedPages)
        assertFalse(printer.commands.contains(P.RELEASE_UNIT))
        assertTrue(printer.closed)
    }

    @Test fun syntacticallyValidRejectedInitializationAckStopsBeforeRasterWithoutReplay() {
        val printer = Printer().apply { rejectAck = P.SET_POWER_DOWN }
        val result = run(printer)
        assertEquals("unknown_after_print_command", result.outcome)
        assertEquals("CAPT_COMMAND_REJECTED", result.failureCode)
        assertEquals(0L, result.sentPrintDataBytes)
        assertEquals(0, printer.descriptors)
        assertEquals(1, printer.commands.count { it == P.RESERVE_UNIT })
        assertFalse(printer.commands.contains(P.SET_JOB_INFO2))
        assertEquals(false, result.protocolDiagnostics["releaseAcknowledged"])
        assertTrue(printer.closed)
    }

    @Test fun rejectedEndOrReleasePreservesConfirmedSheetsWithoutClaimingJobSuccess() {
        for (command in listOf(P.SET_JOB_INFO2, P.RELEASE_UNIT)) {
            val printer = Printer()
            // Set rejection only once all pages have been confirmed.
            val result = run(printer, checkpoint = {
                if (it.printerConfirmedPages == 3) printer.rejectAck = command
            })
            assertEquals("unknown_after_print_command", result.outcome)
            assertEquals(3, result.printerConfirmedPages)
            assertEquals("CAPT_COMMAND_REJECTED", result.failureCode)
            assertEquals(false, result.protocolDiagnostics["releaseAcknowledged"])
            assertEquals(command == P.RELEASE_UNIT, result.protocolDiagnostics["endAcknowledged"])
            assertEquals(1, printer.commands.count { it == P.RESERVE_UNIT })
            assertEquals(if (command == P.RELEASE_UNIT) 1 else 0, printer.commands.count { it == P.RELEASE_UNIT })
            assertTrue(printer.closed)
        }
    }

    @Test fun cancelBeforeOpenDoesNotClaimUsbOrSendAnything() {
        val printer = Printer()
        assertEquals("failed_before_print_commands", run(printer, cancelled = { true }).outcome)
        assertTrue(printer.commands.isEmpty())
        assertFalse(printer.closed) // never opened
    }
}
